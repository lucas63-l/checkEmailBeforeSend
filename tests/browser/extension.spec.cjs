const { test, expect, chromium } = require('@playwright/test');
const path = require('node:path');
const fs = require('node:fs');
const os = require('node:os');
const project = path.resolve(__dirname, '../..');

test('real unpacked extension: automatic Gmail-origin injection, storage, options and analysis transport', async () => {
  test.setTimeout(60000);
  const binaries = fs.readdirSync(path.join(project, '.playwright-browsers')).filter(name => /^chromium-\d+$/u.test(name)).sort();
  const executablePath = path.join(project, '.playwright-browsers', binaries.at(-1), 'chrome-win64', 'chrome.exe');
  const profile = fs.mkdtempSync(path.join(os.tmpdir(), 'draft-check-test-'));
  const context = await chromium.launchPersistentContext(profile, {
    executablePath,
    headless: true,
    args: [`--disable-extensions-except=${project}`, `--load-extension=${project}`]
  });
  try {
    const workers = context.serviceWorkers();
    const worker = workers[0] || await context.waitForEvent('serviceworker');
    const id = new URL(worker.url()).host;
    const page = await context.newPage();
    await page.route('https://mail.google.com/**', route => route.fulfill({ contentType: 'text/html', body: '<html><body><div class="M9"><input name="subjectbox" value="Internship interest at Other Company"><span email="recipient@example.test" name="Recipient">Recipient</span><div class="aQH"></div><div role="textbox" contenteditable="true" g_editable="true">Hi Recipient,<br>I am interested in an internship at Example Company. [NAME]</div></div></body></html>' }));
    await page.goto('https://mail.google.com/mail/u/0/');
    const button = page.getByRole('button', { name: 'Check draft', exact: true });
    await expect(button).toHaveCount(1);
    await button.click();
    await expect(page.getByRole('status')).toContainText('1 confirmed');
    await expect(page.locator('body')).toContainText('interest at Other Company');
    const legacy = { revision: 0, facts: [{ email: 'recipient@example.test', name: 'Recipient', company: 'Example Company', role: 'research internship', location: 'City A', date: '2026-12-01', time: '10:00 UTC', aliases: ['Recipient Alias', '你好 👩🏽‍💻\r\n é  '], companyAliases: ['Example Company Ltd', 'B\\"\r\n Ltd'] }] };
    await worker.evaluate(value => chrome.storage.local.set({ recipientContext: value }), legacy);
    await page.getByRole('button', { name: 'Recipient facts' }).click();
    await expect.poll(() => context.pages().some(p => p.url() === `chrome-extension://${id}/options.html`)).toBe(true);
    const options = context.pages().find(p => p.url().endsWith('/options.html'));
    await expect(options.getByLabel('Recipient email')).toHaveValue('recipient@example.test');
    expect(await worker.evaluate(() => chrome.storage.local.get('recipientContext'))).toEqual({ recipientContext: legacy });
    await options.getByRole('button', { name: 'Save opportunities', exact: true }).click();
    await expect(options.getByRole('status')).toContainText('Saved revision 1');
    const migrated = await worker.evaluate(async () => (await chrome.storage.local.get('recipientContext')).recipientContext);
    expect(migrated.version).toBe(2);
    expect(migrated.facts.map(({ id, ...fact }) => fact)).toEqual(legacy.facts);
    await expect(page.getByRole('status')).toContainText('stale');
    const nameAliases = options.locator('[data-aliases="aliases"]').first();
    await nameAliases.getByRole('button', { name: 'Add alias', exact: true }).click();
    await nameAliases.getByLabel('Alias', { exact: true }).last().fill('Temporary alias\nsecond line');
    await nameAliases.getByRole('button', { name: 'Remove alias', exact: true }).last().click();
    await expect(nameAliases.getByLabel('Alias', { exact: true })).toHaveCount(2);
    await expect(nameAliases.getByRole('button', { name: 'Add alias', exact: true })).toBeFocused();
    await options.getByRole('button', { name: 'Add opportunity', exact: true }).click();
    await options.getByLabel('Recipient email').nth(1).fill('recipient@example.test');
    await options.getByLabel('Company', { exact: true }).nth(1).fill('Other Company');
    await options.getByLabel('Role', { exact: true }).nth(1).fill('sales position');
    await options.getByRole('button', { name: 'Save opportunities', exact: true }).click();
    await expect(options.getByRole('status')).toContainText('Saved revision 2');
    const saved = await worker.evaluate(async () => (await chrome.storage.local.get('recipientContext')).recipientContext);
    expect(saved.facts).toHaveLength(2);
    const firstId = saved.facts[0].id;
    const secondId = saved.facts[1].id;
    await expect(page.getByRole('combobox')).toHaveValue('');
    await page.locator('[name="subjectbox"]').fill('Application for the sales position at Other Company');
    await page.locator('[contenteditable]').fill('I’m applying for the research internship at Example Company in City A.');
    await page.getByRole('combobox').selectOption(firstId);
    await button.click();
    await expect(page.getByRole('status')).toContainText('to review');
    await expect(page.locator('article')).toContainText(['company', 'different companies', 'role', 'different roles']);
    await page.getByRole('button', { name: 'Close results' }).click();
    await page.evaluate(() => {
      const root = document.querySelector('.M9');
      const second = root.cloneNode(true);
      second.querySelector('[data-draft-check]')?.remove();
      second.querySelector('[contenteditable]').textContent = 'I’m applying for the sales position at Other Company.';
      second.id = 'second';
      document.body.append(second);
    });
    await expect(page.getByRole('combobox')).toHaveCount(2);
    await expect(page.locator('#second').getByRole('combobox')).toBeEnabled();
    await page.locator('#second').getByRole('combobox').selectOption(secondId);
    await page.locator('#second').getByRole('button', { name: 'Check draft', exact: true }).click();
    await expect(page.locator('#second').getByRole('status')).toHaveText('No inconsistencies found in the completed checks.');
    await page.locator('#second').getByRole('button', { name: 'Close results' }).click();
    expect(await page.getByRole('combobox').first().inputValue()).toBe(firstId);
    const other = await context.newPage();
    await other.goto(`chrome-extension://${id}/options.html`);
    await expect(other.getByRole('status')).toContainText('Loaded revision 2');
    await options.getByLabel('Recipient name', { exact: true }).first().fill('Recipient Alias');
    await options.getByRole('button', { name: 'Save opportunities', exact: true }).click();
    await expect(options.getByRole('status')).toContainText('Saved revision 3');
    await other.getByLabel('Recipient email').first().fill('colleague@other.example');
    await other.getByRole('button', { name: 'Save opportunities', exact: true }).click();
    await expect(other.getByRole('status')).toContainText('Not saved');
    await expect(other.getByLabel('Recipient email').first()).toHaveValue('colleague@other.example');
    await other.getByRole('button', { name: 'Verify saved state (keep edits)', exact: true }).click();
    await expect(other.getByRole('status')).toContainText('Verified saved revision 3');
    await expect(other.getByLabel('Recipient email').first()).toHaveValue('colleague@other.example');
    await expect(other.getByRole('button', { name: 'Save opportunities', exact: true })).toBeDisabled();
    await expect(other.getByRole('status')).toContainText('prevent overwriting');
    await other.getByRole('button', { name: 'Discard edits and reload' }).click();
    await expect(other.getByRole('status')).toContainText('Loaded revision 3');
    await expect(other.getByLabel('Recipient name', { exact: true }).first()).toHaveValue('Recipient Alias');
    await other.clock.install();
    await other.evaluate(() => {
      const original = chrome.runtime.sendMessage;
      window.restoreMessaging = () => chrome.runtime.sendMessage = original;
      chrome.runtime.sendMessage = message => message.type === 'context:save' ? original(message).then(() => new Promise(() => {})) : original(message);
    });
    await other.getByLabel('Recipient name', { exact: true }).first().fill('Pending 👩🏽‍💻');
    await other.getByRole('button', { name: 'Save opportunities', exact: true }).click();
    await expect.poll(() => worker.evaluate(async () => (await chrome.storage.local.get('recipientContext')).recipientContext.revision)).toBe(4);
    await other.clock.fastForward(8100);
    await expect(other.getByRole('status')).toContainText('Save outcome unconfirmed');
    await expect(other.getByLabel('Recipient name', { exact: true }).first()).toHaveValue('Pending 👩🏽‍💻');
    await expect(other.getByRole('button', { name: 'Save opportunities', exact: true })).toBeDisabled();
    await other.evaluate(() => window.restoreMessaging());
    await other.getByRole('button', { name: 'Verify saved state (keep edits)', exact: true }).click();
    await expect(other.getByRole('status')).toContainText('Verified saved revision 4');
    await other.getByRole('button', { name: 'Save opportunities', exact: true }).click();
    await expect(other.getByRole('status')).toContainText('Saved revision 5');
    const recovered = await worker.evaluate(async () => (await chrome.storage.local.get('recipientContext')).recipientContext);
    expect(recovered.facts).toHaveLength(2);
    expect(recovered.facts[0].name).toBe('Pending 👩🏽‍💻');
    expect(recovered.facts[0].aliases).toEqual(legacy.facts[0].aliases);
    await other.getByRole('button', { name: 'Remove opportunity', exact: true }).nth(1).click();
    await other.getByRole('button', { name: 'Save opportunities', exact: true }).click();
    await expect(other.getByRole('status')).toContainText('Saved revision 6');
    await expect(page.locator('#second').getByRole('combobox')).toHaveValue('');
    await expect(page.locator('#second').getByRole('status')).toContainText('stale');
    expect((await worker.evaluate(async () => (await chrome.storage.local.get('recipientContext')).recipientContext)).facts).toHaveLength(1);
    await other.getByRole('button', { name: 'Add opportunity', exact: true }).click();
    await other.getByLabel('Company', { exact: true }).nth(1).fill('Unknown-contact company');
    await other.getByLabel('Role', { exact: true }).nth(1).fill('analyst role');
    await other.getByRole('button', { name: 'Save opportunities', exact: true }).click();
    await expect(other.getByRole('status')).toContainText('Saved revision 7');
    const valid = await worker.evaluate(async () => (await chrome.storage.local.get('recipientContext')).recipientContext);
    expect(valid.facts[1]).toEqual({ id: valid.facts[1].id, company: 'Unknown-contact company', role: 'analyst role' });
    await expect(page.locator('#second').getByRole('combobox').locator('option').last()).toContainText('Unknown recipient');
    const malformed = { revision: 7, facts: [{ email: 'recipient@example.test', unsupported: 'retain this record' }] };
    await worker.evaluate(value => chrome.storage.local.set({ recipientContext: value }), malformed);
    await other.getByRole('button', { name: 'Verify saved state (keep edits)', exact: true }).click();
    await expect(other.getByRole('status')).toContainText('Incomplete: Unknown recipient field');
    await expect(other.getByLabel('Recipient name', { exact: true }).first()).toHaveValue('Pending 👩🏽‍💻');
    await expect(other.getByRole('button', { name: 'Save opportunities', exact: true })).toBeDisabled();
    expect(await worker.evaluate(async () => (await chrome.storage.local.get('recipientContext')).recipientContext)).toEqual(malformed);
    await worker.evaluate(value => chrome.storage.local.set({ recipientContext: value }), valid);
    const session = await context.newCDPSession(page);
    await session.send('ServiceWorker.enable');
    await session.send('ServiceWorker.stopAllWorkers');
    await other.getByRole('button', { name: 'Verify saved state (keep edits)', exact: true }).click();
    await expect(other.getByRole('status')).toContainText('Verified saved revision 7');
    expect(JSON.parse(await other.locator('#committed').textContent())).toEqual(valid);
    await page.locator('#second [contenteditable]').fill('[NAME]');
    await page.locator('#second').getByRole('button', { name: 'Check draft', exact: true }).click();
    await expect(page.locator('#second').getByRole('status')).toContainText('1 confirmed');
    const screenshot = path.join(project, 'test-results', 'extension-check.png');
    await page.screenshot({ path: screenshot, fullPage: true });
  } finally {
    await context.close();
    const resolved = path.resolve(profile);
    if (path.dirname(resolved) !== path.resolve(os.tmpdir()) || !path.basename(resolved).startsWith('draft-check-test-')) throw new Error('Unexpected temporary profile path.');
    fs.rmSync(resolved, { recursive: true, force: true });
  }
});
